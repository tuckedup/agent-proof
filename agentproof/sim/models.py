"""Simulation models and trajectory representations for agentproof."""

import uuid
from enum import Enum
from typing import Any, Dict, List, Optional, Union

from pydantic import BaseModel, Field

from agentproof.tasks.task import Task


class SimulationMode(str, Enum):
    """Supported simulation orchestration modes."""

    DUAL = "dual"
    NO_USER = "no_user"
    ORACLE_PLAN = "oracle_plan"


class TurnRole(str, Enum):
    """Role associated with a turn or message in the simulation."""

    AGENT = "agent"
    USER = "user"
    SYSTEM = "system"
    TOOL = "tool"


class EpisodeStatus(str, Enum):
    """Lifecycle terminal status of an evaluation episode."""

    COMPLETED = "completed"
    FAILED = "failed"
    MAX_TURNS_EXCEEDED = "max_turns_exceeded"
    ERROR = "error"


class ToolCallRecord(BaseModel):
    """Record of an individual tool call executed during a simulation turn."""

    call_id: str = Field(
        default_factory=lambda: f"call_{uuid.uuid4().hex[:12]}",
        description="Unique identifier for this tool call invocation."
    )
    tool_name: str = Field(description="Name of the invoked tool.")
    caller: Union[TurnRole, str] = Field(
        description="Caller role requesting the tool execution, typically 'agent' or 'user'."
    )
    arguments: Dict[str, Any] = Field(
        default_factory=dict,
        description="Dictionary of input arguments passed to the tool function."
    )
    result: Union[Dict[str, Any], str, Any] = Field(
        default_factory=dict,
        description="Execution output or error payload returned by the tool."
    )
    is_error: bool = Field(
        default=False,
        description="True if tool execution failed, was denied, or encountered an error."
    )
    latency_ms: float = Field(
        default=0.0,
        description="Execution time of the tool call in milliseconds."
    )


class TurnRecord(BaseModel):
    """Record of a single dialogue turn in the simulation episode."""

    turn_index: int = Field(description="Zero-indexed turn order number within the episode.")
    speaker: Union[TurnRole, str] = Field(
        description="Speaker role for this turn, typically 'agent' or 'user'."
    )
    content: str = Field(
        default="",
        description="Text message content generated by the speaker."
    )
    tool_calls: List[ToolCallRecord] = Field(
        default_factory=list,
        description="List of tool calls executed during this turn."
    )
    duration_ms: float = Field(
        default=0.0,
        description="Total duration taken to execute this turn in milliseconds."
    )


class EpisodeTrajectory(BaseModel):
    """Complete trajectory and provenance artifact for a simulation episode."""

    episode_id: str = Field(
        default_factory=lambda: f"ep_{uuid.uuid4().hex[:12]}",
        description="Unique identifier for the simulation episode."
    )
    task_id: str = Field(description="Identifier of the task evaluated in this episode.")
    mode: SimulationMode = Field(description="Orchestration mode used for this run.")
    agent_name: str = Field(description="Name or model string of the evaluated agent.")
    status: Union[EpisodeStatus, str] = Field(
        default=EpisodeStatus.COMPLETED,
        description="Terminal status of the episode, e.g. 'completed', 'max_turns_exceeded'."
    )
    turns: List[TurnRecord] = Field(
        default_factory=list,
        description="Chronological list of all turns executed in this episode."
    )
    db_diff: Dict[str, Any] = Field(
        default_factory=dict,
        description="State diff of database modifications between initial and final snapshots."
    )
    total_cost_usd: float = Field(
        default=0.0,
        description="Total estimated LLM monetary cost in USD across all calls."
    )
    total_prompt_tokens: int = Field(
        default=0,
        description="Total prompt tokens consumed during this episode."
    )
    total_completion_tokens: int = Field(
        default=0,
        description="Total completion tokens generated during this episode."
    )
    duration_ms: float = Field(
        default=0.0,
        description="Total wall-clock execution duration in milliseconds."
    )
    trace_id: Optional[str] = Field(
        default=None,
        description="OpenTelemetry or deterministic trace ID for distributed tracing."
    )
    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Additional contextual metadata, configuration, or evaluation tags."
    )


__all__ = [
    "SimulationMode",
    "TurnRole",
    "EpisodeStatus",
    "ToolCallRecord",
    "TurnRecord",
    "EpisodeTrajectory",
    "Task",
]
